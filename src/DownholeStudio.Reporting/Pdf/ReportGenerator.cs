    private static void Methodology(PdfLayout pdf, ReportContext ctx)
    {
        var sc = ctx.Project.ActiveScenario;
        var r = ctx.Result;
        pdf.Heading("7  Processing methodology");
        pdf.Paragraph("All processing is non-destructive: the original records are kept unchanged in the project and every operation below is applied to a copy of the recorded samples. Arrival times are measured from the recorded trigger.");
        pdf.Heading("Processing applied", 2);
        foreach (var (name, p) in new[] { ("Vertical (P)", sc.VerticalPipeline), ("Horizontal (S)", sc.HorizontalPipeline), ("Reference channel", sc.ReferencePipeline) })
        {
            var steps = p.Steps.Where(s => s.Enabled).ToList();
            pdf.Paragraph($"• {name}: " + (steps.Count == 0 ? "raw data (no processing)" : string.Join(" → ", steps.Select(s => s.DisplayName + (s.DescribeParameters().Count > 0 ? " [" + string.Join(", ", s.DescribeParameters().Select(kv => $"{kv.Key}={kv.Value}")) + "]" : "")))));
        }

        var adjusted = sc.TraceAdjustments.Count(a => a.Value.ReversePolarity || a.Value.TimeShift != 0 || a.Value.Excluded);
        if (adjusted > 0)
        {
            pdf.Paragraph($"• {adjusted} individual trace adjustment(s) (polarity reversal, static time shift or exclusion) are listed in the processing history.");
        }

        pdf.Heading("Picking", 2);
        var all = sc.PPicks.Values.Concat(sc.SPicks.Values).Where(p => p.HasTime).ToList();
        pdf.Paragraph($"• {all.Count(p => p.Origin == PickOrigin.Manual)} manual pick(s), {all.Count(p => p.Origin == PickOrigin.AcceptedSuggestion)} automatic pick(s) reviewed and accepted, {all.Count(p => p.Origin == PickOrigin.Automatic)} automatic pick(s) not individually reviewed.");
        pdf.Paragraph($"• Automatic P picker: {sc.PPicker.Algorithm}; automatic S picker: {sc.SPicker.Algorithm}. Each automatic pick carries a confidence score built from signal-to-noise ratio, onset sharpness, agreement between algorithms, consistency with neighbouring depths and (S) opposite-polarity agreement.");
        pdf.Paragraph(sc.SWave.PickTrace == SPickTrace.Difference
            ? "• S arrivals were picked on the half-difference of the opposite-direction shots, (S⁺ − S⁻)/2, which keeps energy that reverses polarity with the source direction (shear waves) and suppresses energy that does not (P waves, noise common to both)."
            : $"• S arrivals were picked on the {sc.SWave.PickTrace} shot trace.");
        pdf.Paragraph(sc.SWave.Component switch
        {
            SComponentMode.Rotated => $"• Horizontal components were rotated per depth by the angles chosen by the analyst ({sc.SWave.StationRotation.Count} depth(s); range {(sc.SWave.StationRotation.Count > 0 ? $"{sc.SWave.StationRotation.Values.Min():0.#}°–{sc.SWave.StationRotation.Values.Max():0.#}°" : "—")}). Rotation was never applied automatically.",
            SComponentMode.HorizontalY => "• S analysis used horizontal component Y as recorded (no rotation).",
            _ => "• S analysis used horizontal component X as recorded (no rotation).",
        });
        pdf.Heading("Trigger correction", 2);
        pdf.Paragraph(sc.Trigger.Mode switch
        {
            TriggerCorrectionMode.SubtractReferenceOnset => $"Arrival times were corrected with the reference (trigger) geophone: t = t_raw − t_reference + {sc.Trigger.ExpectedReferenceTime * 1000:0.###} ms. Both raw and corrected times are listed in Appendix A.",
            TriggerCorrectionMode.AlignToReferenceMedian => "Shot-to-shot trigger jitter was removed by aligning each record's reference onset to the median reference onset: t = t_raw − (t_reference − median). Both raw and corrected times are listed in Appendix A.",
            _ => "No trigger correction was applied; arrival times are used as recorded.",
        });
        pdf.Heading("Velocity analysis", 2);
        pdf.Paragraph($"Method: {r.MethodDescription}. Regression: {(sc.Analysis.Regression == RegressionMethod.RobustHuber ? $"robust Huber M-estimator (k = {sc.Analysis.HuberThreshold:0.###})" : "ordinary least squares")}.");
        pdf.Paragraph("Straight-ray geometry: slant distance R = √((z − z_s)² + x²) and vertical-equivalent travel time t_v = t·(z − z_s)/R, where z is receiver depth, z_s source depth and x the horizontal source offset. " +
                      "Layer regression fits t_v = a + z/V within each interpreted layer (receivers on a boundary are used by both layers). Pseudo-interval velocity is Δz/Δt_v and true-interval velocity ΔR/Δt between adjacent receivers; " +
                      "both assume straight rays and are biased where rays are oblique below slower layers. The refracted-ray method traces Snell's-law rays through the layer model and solves each layer's velocity downwards (layer stripping); head waves are not modelled.");
        pdf.Paragraph("Vs30 = 30 / Σ(hᵢ/Vsᵢ) over the top 30 m (time-averaged). Poisson's ratio ν = (Vp² − 2Vs²)/(2(Vp² − Vs²)); G = ρVs²; E = 2G(1 + ν); K = ρ(Vp² − 4Vs²/3).");
        pdf.Heading("Density", 2);
        pdf.Paragraph(sc.Density.Source switch
        {
            DensitySource.Constant => $"A constant density of {ctx.Units.Format(sc.Density.ConstantDensity, Quantity.Density)} entered by the user was used for all layers.",
            DensitySource.Estimated => $"Density was ESTIMATED from Vp with {(sc.Density.EstimationMethod == DensityEstimationMethod.Gardner1974 ? "Gardner et al. (1974)" : "Brocher (2005)")}. Estimated densities and the moduli derived from them are marked as estimated; these relations were calibrated on rocks and are approximate for soils.",
            _ => "Densities entered by the user for each layer were used. Moduli are not reported for layers without a density.",
        });
    }

