/// <summary>Generates the professional PDF report with the Skia PDF back end.</summary>
public sealed class ReportGenerator
{
    public byte[] Generate(ReportContext ctx, CancellationToken ct = default)
    {
        var style = new PageStyle { Paper = ctx.Paper };
        // Pass 1: count pages.
        var recorder = new SKPictureRecorder();
        var countLayout = new PdfLayout(() => recorder.BeginRecording(new SKRect(0, 0, style.Size.Width, style.Size.Height)),
            () => recorder.EndRecording().Dispose(), style, Chrome(ctx), 0);
        Build(countLayout, ctx, ct);
        countLayout.Finish();
        var total = countLayout.PageCount;
        recorder.Dispose();

        // Pass 2: render.
        using var stream = new MemoryStream();
        using (var wstream = new SKManagedWStream(stream))
        using (var doc = SKDocument.CreatePdf(wstream, new SKDocumentPdfMetadata
        {
            Title = ReportTitle(ctx), Author = ctx.Project.Report.PreparedBy ?? ctx.GeneratedBy ?? "", Subject = "Downhole seismic survey report",
            Creator = $"Downhole Studio {ctx.AppVersion}", Producer = "Downhole Studio", Creation = ctx.GeneratedAt.UtcDateTime, Modified = ctx.GeneratedAt.UtcDateTime,
            RasterDpi = 300,
        }))
        {
            var layout = new PdfLayout(() => doc.BeginPage(style.Size.Width, style.Size.Height), doc.EndPage, style, Chrome(ctx), total);
            Build(layout, ctx, ct);
            layout.Finish();
            doc.Close();
        }

        return stream.ToArray();
    }

    /// <summary>Renders report pages to PNG images for an on-screen preview (identical layout to the PDF).</summary>
    public IReadOnlyList<byte[]> RenderPreview(ReportContext ctx, float scale = 1.25f, int maxPages = 40, CancellationToken ct = default)
    {
        var style = new PageStyle { Paper = ctx.Paper };
        var pictures = new List<SKPicture>();
        using var recorder = new SKPictureRecorder();
        var counting = new PdfLayout(() => recorder.BeginRecording(new SKRect(0, 0, style.Size.Width, style.Size.Height)), () => recorder.EndRecording().Dispose(), style, Chrome(ctx), 0);
        Build(counting, ctx, ct);
        counting.Finish();
        var total = counting.PageCount;
        var layout = new PdfLayout(() => recorder.BeginRecording(new SKRect(0, 0, style.Size.Width, style.Size.Height)), () => pictures.Add(recorder.EndRecording()), style, Chrome(ctx), total);
        Build(layout, ctx, ct);
        layout.Finish();
        var images = new List<byte[]>();
        foreach (var picture in pictures.Take(maxPages))
        {
            var info = new SKImageInfo((int)(style.Size.Width * scale), (int)(style.Size.Height * scale));
            using var surface = SKSurface.Create(info);
            surface.Canvas.Clear(SKColors.White);
            surface.Canvas.Scale(scale);
            surface.Canvas.DrawPicture(picture);
            using var image = surface.Snapshot();
            using var data = image.Encode(SKEncodedImageFormat.Png, 90);
            images.Add(data.ToArray());
        }

        foreach (var p in pictures)
        {
            p.Dispose();
        }

        return images;
    }

    private static string ReportTitle(ReportContext ctx) => ctx.Project.Report.Title ?? $"Downhole Seismic Survey — {ctx.Project.Metadata.Name}";

    private static PageChrome Chrome(ReportContext ctx)
    {
        var b = ctx.Project.Report.Branding;
        return new PageChrome(b.CompanyName ?? "Downhole seismic survey report", $"{ctx.Project.Metadata.Name}{(ctx.Project.Metadata.JobNumber is { } j ? " · " + j : "")}",
            b.Footer ?? $"Generated by Downhole Studio {ctx.AppVersion}", $"Rev. {ctx.Project.Report.Revision ?? "0"} · {ctx.GeneratedAt:yyyy-MM-dd}");
    }

    private void Build(PdfLayout pdf, ReportContext ctx, CancellationToken ct)
    {
        var report = ctx.Project.Report;
        var on = report.Sections.ToHashSet();
        var theme = PlotTheme.Print;
        var sections = new (ReportSection Section, Action Write)[]
        {
            (ReportSection.CoverPage, () => Cover(pdf, ctx)),
            (ReportSection.ProjectInformation, () => ProjectInfo(pdf, ctx)),
            (ReportSection.ClientInformation, () => Client(pdf, ctx)),
            (ReportSection.SiteInformation, () => Site(pdf, ctx)),
            (ReportSection.SurveyConfiguration, () => SurveyConfig(pdf, ctx)),
            (ReportSection.InstrumentInformation, () => Instruments(pdf, ctx)),
            (ReportSection.SurveyGeometry, () => Geometry(pdf, ctx, theme)),
            (ReportSection.ProcessingMethodology, () => Methodology(pdf, ctx)),
            (ReportSection.QualityControl, () => Quality(pdf, ctx)),
            (ReportSection.PWaveAnalysis, () => WaveSection(pdf, ctx, WaveType.P, theme)),
            (ReportSection.SWaveAnalysis, () => WaveSection(pdf, ctx, WaveType.S, theme)),
            (ReportSection.TravelTimeCurves, () => TravelTimes(pdf, ctx, theme)),
            (ReportSection.VelocityProfiles, () => Profiles(pdf, ctx, theme)),
            (ReportSection.LayerModel, () => LayerModel(pdf, ctx)),
            (ReportSection.EngineeringParameters, () => EngineeringSection(pdf, ctx, theme)),
            (ReportSection.Vs30, () => Vs30Section(pdf, ctx)),
            (ReportSection.ProcessingNotes, () => Notes(pdf, "Processing notes", report.ProcessingNotes, "No processing notes were entered.")),
            (ReportSection.Warnings, () => Warnings(pdf, ctx)),
            (ReportSection.Conclusions, () => Conclusions(pdf, ctx)),
            (ReportSection.AppendixPickTable, () => PickAppendix(pdf, ctx)),
            (ReportSection.AppendixProcessingHistory, () => HistoryAppendix(pdf, ctx)),
        };
        foreach (var (section, write) in sections)
        {
            ct.ThrowIfCancellationRequested();
            if (on.Contains(section))
            {
                write();
            }
        }

        if (!on.Contains(ReportSection.CoverPage) && pdf.PageCount == 0)
        {
            pdf.NewPage();
        }
    }

    private static void Cover(PdfLayout pdf, ReportContext ctx)
    {
        var c = pdf.BeginCover();
        var s = pdf.Style;
        var size = s.Size;
        var b = ctx.Project.Report.Branding;
        using (var band = Draw.Fill(SKColor.Parse("#0B0F18")))
        {
            c.DrawRect(new SKRect(0, 0, size.Width, 210), band);
        }

        using (var accent = Draw.Fill(s.Accent))
        {
            c.DrawRect(new SKRect(0, 210, size.Width, 214), accent);
        }

        var x = s.Margin;
        if (ctx.Logo is { Length: > 0 } logo)
        {
            using var img = SKImage.FromEncodedData(logo);
            if (img is not null)
            {
                var h = 54f;
                var w = img.Width * h / img.Height;
                var plate = new SKRect(x - 8, 40, x + Math.Min(w, 220) + 8, 40 + h + 16);
                using var white = Draw.Fill(SKColors.White);
                c.DrawRoundRect(plate, 4, 4, white);
                c.DrawImage(img, new SKRect(x, 48, x + Math.Min(w, 220), 48 + Math.Min(w, 220) * img.Height / img.Width));
            }
        }

        using var company = PlotFonts.Font(12, PlotFonts.SemiBold);
        Draw.Text(c, b.CompanyName ?? "", x, 150, company, SKColors.White);
        using var kicker = PlotFonts.Font(10, PlotFonts.Medium);
        Draw.Text(c, "DOWNHOLE SEISMIC SURVEY REPORT", x, 178, kicker, SKColor.Parse("#FFB289"));

        using var title = PlotFonts.Font(26, PlotFonts.Bold);
        var titleLines = PdfLayout.Wrap(ctx.Project.Report.Title ?? ctx.Project.Metadata.Name, title, pdf.ContentWidth);
        var y = 280f;
        foreach (var line in titleLines)
        {
            Draw.Text(c, line, x, y, title, s.Ink);
            y += 32;
        }

        using var sub = PlotFonts.Font(12);
        var site = ctx.Project.Report.Site.Name;
        Draw.Text(c, (site is null ? "" : site + " · ") + $"Borehole {ctx.Project.Survey.Geometry.Borehole.Name}", x, y + 4, sub, s.Muted);
        y += 50;
        var rows = new List<(string, string?)>
        {
            ("Client", ctx.Project.Report.Client.Name),
            ("Project / job number", string.Join(" · ", new[] { ctx.Project.Metadata.Name, ctx.Project.Metadata.JobNumber }.Where(v => !string.IsNullOrWhiteSpace(v)))),
            ("Survey date", ctx.Project.Metadata.SurveyDate?.ToString("MMMM d, yyyy", CultureInfo.InvariantCulture)),
            ("Report date", ctx.GeneratedAt.ToString("MMMM d, yyyy", CultureInfo.InvariantCulture)),
            ("Prepared by", ctx.Project.Report.PreparedBy ?? b.EngineerName),
            ("Checked by", ctx.Project.Report.CheckedBy),
            ("Registration / licence", b.Registration),
            ("Revision", ctx.Project.Report.Revision),
        };
        using var kf = PlotFonts.Font(9.5f, PlotFonts.Medium);
        using var vf = PlotFonts.Font(10.5f);
        foreach (var (k, v) in rows.Where(r => !string.IsNullOrWhiteSpace(r.Item2)))
        {
            Draw.Text(c, k, x, y, kf, s.Muted);
            Draw.Text(c, v!, x + 170, y, vf, s.Ink);
            y += 20;
        }

        // Reproducibility block.
        var r = ctx.Result;
        var box = new SKRect(x, size.Height - 250, size.Width - s.Margin, size.Height - 120);
        using (var shade = Draw.Fill(s.Shade))
        {
            c.DrawRoundRect(box, 4, 4, shade);
        }

        using var small = PlotFonts.Font(8.5f);
        using var smallBold = PlotFonts.Font(8.5f, PlotFonts.SemiBold);
        var repro = new[]
        {
            ("Software", $"Downhole Studio {ctx.AppVersion}"),
            ("Analysis date", r.CalculatedAt.ToString("yyyy-MM-dd HH:mm 'UTC'zzz", CultureInfo.InvariantCulture)),
            ("Velocity method", $"{r.MethodDescription}; {(ctx.Project.ActiveScenario.Analysis.Regression == RegressionMethod.RobustHuber ? "robust (Huber) regression" : "ordinary least squares")}"),
            ("Scenario", ctx.Project.ActiveScenario.Name),
            ("Data coverage", r.Qc.Summary.MinDepth is { } a ? $"{ctx.Units.Format(a, Quantity.Length)} – {ctx.Units.Format(r.Qc.Summary.MaxDepth, Quantity.Length)}, {r.Qc.Summary.Stations} depths" : "—"),
            ("Analysis quality", $"{Quality(r.Qc.Quality)} — {string.Join(" ", r.Qc.QualityReasons.Take(2))}"),
            ("Generated by", ctx.GeneratedBy ?? "—"),
        };
        var ry = box.Top + 18;
        foreach (var (k, v) in repro)
        {
            Draw.Text(c, k, box.Left + 12, ry, smallBold, s.Muted);
            foreach (var line in PdfLayout.Wrap(v, small, box.Width - 150).Take(2))
            {
                Draw.Text(c, line, box.Left + 130, ry, small, s.Ink);
                ry += 11.5f;
            }

            ry += 3;
        }

        using var disc = PlotFonts.Font(7.5f, PlotFonts.Italic);
        var dy = size.Height - 100f;
        foreach (var line in PdfLayout.Wrap(Disclaimer, disc, pdf.ContentWidth))
        {
            Draw.Text(c, line, x, dy, disc, s.Muted);
            dy += 10;
        }
    }

