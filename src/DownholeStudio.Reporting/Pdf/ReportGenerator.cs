    private static void Warnings(PdfLayout pdf, ReportContext ctx)
    {
        pdf.Heading("17  Warnings");
        var flags = ctx.Result.Qc.Flags.Where(f => f.Severity != Severity.Information).OrderByDescending(f => f.Severity).ThenBy(f => f.Depth ?? -1).ToList();
        if (flags.Count == 0)
        {
            pdf.Paragraph("No warnings were raised by the automatic quality checks.");
            return;
        }

        var table = new ResultTable("Warnings", [new("Severity", Numeric: false), new("Depth", Quantity.Length, 2), new("Finding", Numeric: false)]);
        foreach (var f in flags)
        {
            table.Add(f.Severity == Severity.Error ? "Likely problem" : "Review", f.Depth, f.Message);
        }

        pdf.Table(table, ctx.Units, [1, 0.8f, 6]);
    }

