#!/usr/bin/env bash
# Starts (or updates) the Downhole Studio local test environment and prints the addresses.
#   testenv/start.sh [--rebuild-app]     --rebuild-app republishes the Linux build of the application
# Everything runs in Docker under the project name "dhs-testenv". Secrets are generated into
# testenv/.env (git-ignored). The licence server signs with the production keys from the folder named
# by SIGNING_KEYS_DIR in server/.env, so the application accepts its trials and licences.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(dirname "$HERE")"
cd "$ROOT"
REBUILD=0; [ "${1:-}" = "--rebuild-app" ] && REBUILD=1
rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "$1"; }

if [ ! -f "$HERE/.env" ]; then
  KEYS="$(grep -oP '^SIGNING_KEYS_DIR=\K.*' server/.env 2>/dev/null || true)"
  [ -n "$KEYS" ] && [ -f "$KEYS/license-signing-key.pem" ] || { echo "Set SIGNING_KEYS_DIR in server/.env to the folder with the signing keys."; exit 1; }
  umask 077
  cat > "$HERE/.env" <<ENV
# Generated by testenv/start.sh for the local test environment. Never commit this file.
POSTGRES_PASSWORD=$(rand 32)
LICENSING_KEY_PEPPER=$(openssl rand -hex 32)
SIGNING_KEYS_DIR=$KEYS
HOST_UID=$(id -u)
HOST_GID=$(id -g)
VNC_PASSWORD=$(rand 8)
ADMIN_EMAIL=admin@quakelogic.test
ADMIN_PASSWORD=$(rand 20)
FILES_USER=tester
FILES_PASSWORD=$(rand 16)
ENV
fi
set -a; source "$HERE/.env"; set +a
[ -f .tools/env.sh ] || scripts/setup-dev.sh
source .tools/env.sh

if [ "$REBUILD" = 1 ] || [ ! -x artifacts/publish/linux-x64/DownholeStudio ]; then
  echo "== Publishing the Linux build"
  dotnet publish src/DownholeStudio.App -c Release -r linux-x64 --self-contained true -p:DebugType=none -o artifacts/publish/linux-x64 -v q
fi
echo "== Staging the application image"
CTX=artifacts/testenv/context; rm -rf "$CTX"; mkdir -p "$CTX/app/Samples" "$CTX/testenv"
cp -a artifacts/publish/linux-x64/. "$CTX/app/"
cp "packaging/samples/Downhole Studio Sample.dhsx" "$CTX/app/Samples/"
cp -a testenv/app "$CTX/testenv/"

if [ ! -d artifacts/testenv/test-data ]; then
  echo "== Generating SEG-2 test surveys"
  for d in Clean Noisy MissingTraces TriggerErrors ReversedPolarityS; do
    dotnet run --project tools/DownholeStudio.Cli -v q -- synth --dataset "$d" --out "artifacts/testenv/test-data/$d survey"
  done
fi

cd "$HERE"
docker compose --profile init run --rm -T init
if [ ! -f "$HERE/.files-ready" ]; then
  echo "== Preparing the file browser account"
  docker compose run --rm --no-deps -T files config init --database /database/filebrowser.db >/dev/null
  docker compose run --rm --no-deps -T files users add "$FILES_USER" "$FILES_PASSWORD" --perm.admin --database /database/filebrowser.db >/dev/null
  touch "$HERE/.files-ready"
fi
echo "== Building and starting containers"
docker compose up -d --build --remove-orphans
echo "== Waiting for the licence server"
for _ in $(seq 90); do curl -sf http://127.0.0.1:50011/health >/dev/null && break; sleep 2; done
curl -sf http://127.0.0.1:50011/health >/dev/null || { echo "Licence server did not start; see: docker compose -p dhs-testenv logs license-server"; exit 1; }
for _ in $(seq 30); do curl -s -o /dev/null http://127.0.0.1:50012/ && break; sleep 2; done
printf '%s\n' "$ADMIN_PASSWORD" | docker compose exec -T admin-portal dotnet DownholeStudio.AdminPortal.dll create-admin --email "$ADMIN_EMAIL" --password-stdin >/dev/null 2>&1 || true

HOST="$(hostname -I | awk '{print $1}')"
cat <<INFO

Downhole Studio test environment is running.

  Application (in the browser)  http://$HOST:50010/vnc.html?autoconnect=1&resize=scale   VNC password: $VNC_PASSWORD
  Files (reports, test data)    http://$HOST:50013/   user: $FILES_USER   password: $FILES_PASSWORD
  Admin portal                  http://$HOST:50012/   e-mail: $ADMIN_EMAIL   password: $ADMIN_PASSWORD
  Test mailbox (licence mails)  http://$HOST:50014/
  Licence server API            http://$HOST:50011/   (Windows test PC: Settings > Advanced > Licensing server)

Stop: testenv/stop.sh    Reset all test data: testenv/stop.sh --reset
INFO
